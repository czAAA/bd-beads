// CHANGELOG.md, the owner's history (ticket 1046, spec 1043): generated from the release record and the Release notes,
// never edited by hand. `node scripts/changelog.ts` writes it; `--print` writes it to the terminal with the notes not
// yet released on top, so the owner sees what the next release would hold.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { newerFirst } from '../src/domain/notesFile.ts';
import { numberUnreleased, readNoteFiles, type NoteFile, type NoteFiles } from './notes.ts';
import { nextRelease, type Kind, type NumberedNote } from './versions.ts';

/** The changelog's path in the repo, at its root where a reader of the public repo looks for it. */
export const CHANGELOG = 'CHANGELOG.md';

const KIND_WORDS: Record<Kind, string> = { new: 'New', changed: 'Changed', fixed: 'Fixed' };

const INTRO = [
  '# Changelog',
  '',
  'Every change a maker can see in openbeads, newest first: each Production release with its date, the Versions it released with their Release notes, and at the end the notes from before 1.0.0. How the numbers step is in [docs/agents/pull-requests.md](docs/agents/pull-requests.md) (Release notes).',
  '',
  'This file is generated by `npm run changelog` from `src/data/releases.json` and `src/data/releaseNotes/`; don’t edit it by hand.',
];

const cell = (text: string): string => text.replaceAll('|', '\\|');
const ticket = (note: NoteFile): string => note.name.slice('YYYY-MM-DD-'.length);

/** The notes in blocks, newest first: a block is the notes that share the first and second number, headed by its
 * highest Version and the date of its newest note, with a row per note (Version, kind, line, ticket). */
function blocks(notes: readonly NumberedNote[], files: ReadonlyMap<string, NoteFile>): string[] {
  const file = (note: NumberedNote): NoteFile => {
    const found = files.get(note.name);
    if (!found) throw new Error(`${note.name} is in the release record but its file is gone`);
    return found;
  };
  const byBlock = new Map<string, NumberedNote[]>();
  for (const note of [...notes].sort((a, b) => newerFirst(a.version, b.version) || b.name.localeCompare(a.name))) {
    const block = note.version.split('.').slice(0, 2).join('.');
    byBlock.set(block, [...(byBlock.get(block) ?? []), note]);
  }
  return [...byBlock.values()].flatMap((rows) => [
    '',
    `### ${rows[0].version} · ${rows.map((note) => file(note).date).sort().at(-1)}`,
    '',
    '| Version | Kind | Change | Ticket |',
    '|---|---|---|---|',
    ...rows.map((note) => `| ${note.version} | ${KIND_WORDS[note.kind]} | ${cell(file(note).line)} | ${ticket(file(note))} |`),
  ]);
}

/** The changelog's text: the released part, and with `unreleased` the notes the next release would hold on top. */
export function changelog(files: NoteFiles, unreleased?: readonly NumberedNote[]): string {
  const byName = new Map(files.notes.map((note) => [note.name, note]));
  const waiting = unreleased
    ? ['', `## Unreleased: what release ${nextRelease(files.record)} would hold`, ...(unreleased.length > 0 ? blocks(unreleased, byName) : ['', 'Nothing yet: the release command refuses until a Release note merges.'])]
    : [];
  const releases = [...files.record].reverse().flatMap((release) => [
    '',
    `## Release ${release.version} · ${release.date}`,
    ...(release.notes.length > 0 ? blocks(release.notes, byName) : ['', 'No Release notes.']),
  ]);
  const before = [
    '',
    '## Before 1.0.0',
    '',
    '| Date | Change | Ticket |',
    '|---|---|---|',
    ...[...files.before].reverse().map((note) => `| ${note.date} | ${cell(note.line)} | ${ticket(note)} |`),
  ];
  return [...INTRO, ...waiting, ...releases, ...before, ''].join('\n');
}

function main(args: string[]): void {
  const root = process.cwd();
  const files = readNoteFiles(root);
  if (args[0] === '--print') {
    process.stdout.write(changelog(files, numberUnreleased(root, files, false)?.notes ?? []));
    return;
  }
  if (args.length > 0) throw new Error('usage: node scripts/changelog.ts [--print]');
  writeFileSync(resolve(root, CHANGELOG), changelog(files));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
